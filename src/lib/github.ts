import type { ChangelogEntry } from "./products";

const REVALIDATE_SECONDS = 3600; // safety-net re-check, in case the webhook is ever missed

export function releaseTag(owner: string, repo: string) {
  return `release:${owner}/${repo}`;
}

type GithubAsset = {
  name: string;
  size: number;
  browser_download_url: string;
};

type GithubRelease = {
  tag_name: string;
  name: string | null;
  body: string | null;
  draft: boolean;
  prerelease: boolean;
  published_at: string | null;
  assets: GithubAsset[];
};

export type LiveRelease = {
  repoUrl: string;
  latestVersion: string;
  downloadUrl: string;
  downloadSize: string;
  changelog: ChangelogEntry[];
};

function formatSize(bytes: number) {
  return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
}

function versionFromTag(tag: string) {
  return tag.replace(/^v/i, "");
}

/**
 * Release bodies are markdown, written either by hand or auto-generated by
 * GitHub (which prefixes them with a redundant "# Release vX.X.X" title).
 * We strip that one line, since the version is already shown by the page
 * itself, and leave everything else as markdown for the page to render.
 */
function cleanReleaseBody(body: string | null): string {
  if (!body || !body.trim()) {
    return "_No release notes were written for this version._";
  }
  return body
    .replace(/\r\n/g, "\n")
    .replace(/^#\s*Release\s+v?[\w.-]+\s*\n?/im, "")
    .trim();
}

function findInstaller(assets: GithubAsset[]) {
  return assets.find(
    (asset) => asset.name.endsWith(".exe") && !asset.name.endsWith(".blockmap")
  );
}

/**
 * Pulls live release data straight from GitHub so the site's version number,
 * download link, and changelog always match whatever's actually been
 * published to the repo, instead of numbers baked in at deploy time.
 * Falls back to the given static snapshot if GitHub can't be reached.
 */
export async function getLiveRelease(
  owner: string,
  repo: string,
  fallback: LiveRelease
): Promise<LiveRelease> {
  try {
    const res = await fetch(
      `https://api.github.com/repos/${owner}/${repo}/releases`,
      {
        headers: { Accept: "application/vnd.github+json" },
        next: {
          revalidate: REVALIDATE_SECONDS,
          tags: [releaseTag(owner, repo)],
        },
      }
    );

    if (!res.ok) return fallback;

    const releases = (await res.json()) as GithubRelease[];
    const published = releases
      .filter((r) => !r.draft && !r.prerelease)
      .sort(
        (a, b) =>
          new Date(b.published_at ?? 0).getTime() -
          new Date(a.published_at ?? 0).getTime()
      );

    if (published.length === 0) return fallback;

    const latest = published[0];
    const installer = findInstaller(latest.assets);

    const changelog: ChangelogEntry[] = published.map((release) => ({
      version: versionFromTag(release.tag_name),
      date: release.published_at
        ? release.published_at.slice(0, 10)
        : "unknown",
      body: cleanReleaseBody(release.body),
    }));

    return {
      repoUrl: `https://github.com/${owner}/${repo}`,
      latestVersion: versionFromTag(latest.tag_name),
      downloadUrl: installer?.browser_download_url ?? fallback.downloadUrl,
      downloadSize: installer ? formatSize(installer.size) : fallback.downloadSize,
      changelog,
    };
  } catch {
    return fallback;
  }
}
